import * as React from "react";
import { cn } from "@/lib/utils";

export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { variant?: "default" | "glass" | "cyber" }
>(({ className, variant = "glass", ...props }, ref) => {
  const variantStyles = {
    default: "bg-slate-900/80 border border-slate-800 text-slate-100",
    glass: "glass-card text-slate-100",
    cyber: "glass-panel-cyan text-slate-100"
  };

  return (
    <div
      ref={ref}
      className={cn("rounded-2xl p-6 transition-all duration-300", variantStyles[variant], className)}
      {...props}
    />
  );
});
Card.displayName = "Card";

